#!/usr/bin/env python3
"""gen_trap_table.py - build host/mon_traps.json (trap name -> A-line trap word).

Source: Retro68's multiversal interfaces (`Multiverse.h`, generated by
Wolfgang Thaller's multiversal project, MIT licence), which declares every trap
as `enum { _Name = 0xAnnn };`. The table is checked in so that mac_debug's
break_trap needs neither Retro68 nor the network at run time.

    /usr/bin/python3 host/tools/gen_trap_table.py \
        ~/Documents/Dev/Retro68-build/toolchain/multiversal/CIncludes/Multiverse.h
"""
import json
import os
import re
import sys

ENUM = re.compile(r"enum \{ _([A-Za-z0-9]+) = 0x([Aa][0-9A-Fa-f]{3}) \};")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mon_traps.json")


def parse(text):
    traps = {}
    for name, word in ENUM.findall(text):
        traps.setdefault(name, int(word, 16))       # first declaration wins
    return traps


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    traps = parse(open(argv[1], encoding="latin-1").read())
    doc = {
        "source": "Retro68 multiversal interfaces, Multiverse.h (MIT licence, (c) 2019 Wolfgang Thaller)",
        "count": len(traps),
        "traps": {k: f"0x{v:04X}" for k, v in sorted(traps.items())},
    }
    with open(OUT, "w") as f:
        json.dump(doc, f, indent=0, sort_keys=False)
        f.write("\n")
    print(f"{len(traps)} traps -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main(sys.argv)
